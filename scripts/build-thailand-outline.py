"""Regenerate src/domain/thailand-outline.ts from Natural Earth data.

The outline comes from the `world-atlas` package (Natural Earth 1:50m, public domain):

    npm pack world-atlas@2.0.2 && mkdir -p /tmp/wa && tar -xzf world-atlas-2.0.2.tgz -C /tmp/wa
    python3 scripts/build-thailand-outline.py /tmp/wa/package/countries-50m.json

It only reads the JSON file; it decodes TopoJSON itself so no third-party code runs.
"""

import json
import sys
from pathlib import Path

topo = json.loads(Path(sys.argv[1]).read_text())
sx, sy = topo["transform"]["scale"]
tx, ty = topo["transform"]["translate"]

arcs = []
for arc in topo["arcs"]:
    x = y = 0
    points = []
    for dx, dy in arc:
        x += dx
        y += dy
        points.append((x * sx + tx, y * sy + ty))
    arcs.append(points)


def ring(arc_ids):
    out = []
    for i in arc_ids:
        a = arcs[i] if i >= 0 else arcs[~i][::-1]
        out.extend(a if not out else a[1:])
    return out


thailand = next(g for g in topo["objects"]["countries"]["geometries"] if g.get("properties", {}).get("name") == "Thailand")
polygons = thailand["arcs"] if thailand["type"] == "MultiPolygon" else [thailand["arcs"]]
rings = sorted((ring(p[0]) for p in polygons), key=len, reverse=True)

lines = [
    "// Generated by scripts/build-thailand-outline.py. Do not edit by hand.",
    "// Outline of Thailand from Natural Earth 1:50m (public domain), via the world-atlas package.",
    "// Each ring is a closed polygon of [longitude, latitude] pairs; the first ring is the mainland.",
    "",
    "export const THAILAND_OUTLINE: readonly (readonly (readonly [number, number])[])[] = [",
]
for r in rings:
    pts = ",".join(f"[{x:.2f},{y:.2f}]" for x, y in r)
    lines.append(f"  [{pts}],")
lines.append("];")
lines.append("")
Path("src/domain/thailand-outline.ts").write_text("\n".join(lines))
print(f"{len(rings)} rings, {sum(len(r) for r in rings)} points")
